export const DICTIONARIES: Record<Locale, Dict> = { es, en };

export function isLocale(value: unknown): value is Locale {
  return value === "es" || value === "en";
}

type Leaves<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : T[K] extends readonly unknown[] ? never : Leaves<T[K], `${P}${K}.`>;
}[keyof T & string];
export type TKey = Leaves<Dict>;

/** Función de traducción para un idioma: t("clock.clockIn"), t("employee.hello", { name }). */
export function translator(locale: Locale) {
  const dict = DICTIONARIES[locale];
  return (key: TKey, vars?: Record<string, string | number>) => {
    const [group, name] = key.split(".") as [keyof Dict, string];
    let text = (dict[group] as Record<string, string>)[name] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}

export type T = ReturnType<typeof translator>;
